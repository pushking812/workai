"""core/name_link.py: слова, связь по наименованию, подсказка сдвига (синтетические данные)."""
from core.name_link import name_match, shift_hints, words


def vor(i, npp, name, razd=""):
    return {"ИдСтроки": i, "ШифрПроекта": "Ш", "НомИзмПроекта": "1", "NПП": npp, "НаименованиеРабот": name, "Раздел": razd}


def so(npp, name, key="K", prim="", row=None):
    return {"ШифрПроекта": "Ш", "НомИзмПроекта": "1", "КлючСО": key, "NПП": npp, "НаименованиеИТехХар": name,
            "Примечание": prim, "Раздел": "", "ИмяФайла": "f", "Таблица": "1", "Строка": row or npp}


def test_words():
    assert words("Хомуты, Ёлка 3-го; А 12 хомут.") == ["хомут", "елка", "3", "12"]


def test_exact_pair():
    v = [vor("a", "1.8", "Речевой автоинформатор настенный")]
    s = [so("1.11", "Речевой автоинформатор")]
    r = name_match(v, s, [])
    assert [(x["Статус"], x["ИдСтроки"], x["NППСО"]) for x in r] == [("по наименованию", "a", "1.11")]


def test_ambiguous_one_record_per_vor_row():
    v = [vor("a", "1.8", "Хомут кабельный нейлоновый черный")]
    s = [so("2.1", "Хомут кабельный нейлоновый", row=1), so("2.2", "Хомут кабельный нейлоновый", row=2)]
    r = name_match(v, s, [])
    assert len(r) == 1 and r[0]["Статус"] == "неоднозначно" and r[0]["СтрокСО"] == 2
    assert r[0]["Номера"] == "2.1, 2.2"


def test_linked_rows_are_not_matched_by_name():
    v = [vor("a", "1.8", "Речевой автоинформатор настенный")]
    s = [so("1.11", "Речевой автоинформатор", key="K1")]
    assert name_match(v, s, [{"ИдСтроки": "a", "КлючСО": "K1"}]) == []


def link(i, npp, name, sonpp, soname, key="K", row=None):
    return {"ИдСтроки": i, "ШифрПроекта": "Ш", "НомИзмПроекта": "1", "NПП": npp, "НаименованиеРабот": name, "NППСО": sonpp,
            "КлючСО": key, "СО_ИмяФайла": "f", "СО_Таблица": "1", "СО_Строка": row or sonpp, "СО_НаименованиеИТехХар": soname}


def test_shift_hint():
    # ВОР 14.12 ссылается на 14.12 СО («Лента»), но по наименованию подходит 14.11 («Хомут кабельный»)
    links = [link("a", "14.12", "Хомут кабельный нейлоновый", "14.12", "Лента монтажная"),
             link("b", "14.13", "Лента монтажная перфорированная", "14.12", "Лента монтажная")]
    s = [so("14.11", "Хомут кабельный", row="14.11"), so("14.12", "Лента монтажная", row="14.12")]
    r = shift_hints(links, s)
    assert [(x["NПП"], x["NППСО"], x["Ссылки"]) for x in r] == [("14.12", "14.11", "14.12")]


def test_no_hint_when_confirmed():
    links = [link("a", "1", "Хомут кабельный нейлоновый", "1", "Хомут кабельный")]
    assert shift_hints(links, [so("1", "Хомут кабельный")]) == []
